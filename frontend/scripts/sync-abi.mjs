// Emits a typed `as const` ABI for viem from the Foundry build.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
const here = dirname(fileURLToPath(import.meta.url))
const src = resolve(here, '../../contracts/out/ClubLedger.sol/ClubLedger.json')
const outDir = resolve(here, '../src/abi')
mkdirSync(outDir, { recursive: true })
const artifact = JSON.parse(readFileSync(src, 'utf8'))
writeFileSync(
  resolve(outDir, 'abi.ts'),
  `// Generated by \`npm run sync-abi\` from contracts/out/ClubLedger.sol/ClubLedger.json — do not edit.\nexport const CLUBLEDGER_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const\n`,
)
console.log('ABI synced:', artifact.abi.length, 'items')
